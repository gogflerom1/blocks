def _smooth(ks, t):
    ks = np.asarray(ks, float)
    ts = ks[:, 0]
    t = np.clip(t, ts[0], ts[-1])
    i = int(np.clip(np.searchsorted(ts, t) - 1, 0, len(ts) - 2))
    u = (t - ts[i]) / (ts[i + 1] - ts[i]); u = u * u * (3 - 2 * u)
    return ks[i, 1:] * (1 - u) + ks[i + 1, 1:] * u


def hero(t): return _smooth(HERO, t)
def ground(t): return _smooth(GROUND, t)
def ball(t): return _smooth(BALL, t)
